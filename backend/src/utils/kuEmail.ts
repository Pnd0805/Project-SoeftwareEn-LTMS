const KU_DOMAIN = 'ku.th';

export function isKuEmail(email : string): boolean {
    const at = email.lastIndexOf('@');
    if(at === -1) return false;
    // ★ โดเมนไม่สนตัวพิมพ์เล็กใหญ่ (RFC 1035) และต้องตรงทั้งก้อน
    //   🔴 endsWith('ku.th') เฉย ๆ ใช้ไม่ได้ — `fake-ku.th` กับ `notku.th` จะผ่านด้วย
    return email.slice(at + 1).trim().toLowerCase() === KU_DOMAIN;
}

/** ตรงข้ามของ `isKuEmail` — เขียนไว้ให้ผู้เรียกอ่านง่าย ไม่ต้องใส่ `!` กลับหัวทุกที่ */
export function isExternalEmail(email : string): boolean {
    return !isKuEmail(email);
}

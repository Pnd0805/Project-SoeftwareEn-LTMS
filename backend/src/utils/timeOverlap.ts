/**
 * ช่วงเวลาสองช่วงทับกันไหม — ตัวเดียวที่ทุกด่าน "คนเดียวอยู่สองที่พร้อมกันไม่ได้" ต้องใช้
 *
 * ★ แยกออกมาเป็น util เพราะกฎนี้ถูกใช้ 3 ที่แล้วและต้องตอบเหมือนกันทุกที่:
 *   ① referee.service assertSchedulable           — กรรมการคนเดียวในทัวร์เดียว
 *   ② referee.service assertNoCrossTournamentConflict — กรรมการข้ามทัวร์ (มติ 6 ต.ค. ทางเลือก ก)
 *   ③ match.service listMyMatches                 — ธงเตือนผู้เล่น/กรรมการในหน้า "แมตช์ของฉัน"
 *   ถ้าเขียนซ้ำในแต่ละที่ แล้ววันหนึ่งมีคนแก้นิยาม "ทับ" ที่เดียว อีกสองที่จะเงียบ ๆ ไม่ตรงกัน
 *
 * ★ ติดกันพอดีไม่นับว่าทับ (เปรียบเทียบแบบ strict `<`)
 *   แมตช์ที่จบ 11:00 กับแมตช์ที่เริ่ม 11:00 ⇒ ไปต่อได้ ไม่ใช่การทับ
 *   ถ้าใช้ `<=` ตารางที่จัดชนกันพอดี (ซึ่งเป็นเรื่องปกติในทัวร์) จะถูกเตือนทั้งวัน
 */
export function timesOverlap(aStart : Date, aEnd : Date, bStart : Date, bEnd : Date): boolean {
    return aStart < bEnd && bStart < aEnd;
}

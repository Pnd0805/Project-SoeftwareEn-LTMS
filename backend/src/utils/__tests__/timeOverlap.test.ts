import { describe, expect, it } from 'vitest';
import { timesOverlap } from '../timeOverlap.js';

/**
 * กฎเดียวที่ทุกด่าน "คนเดียวอยู่สองที่พร้อมกันไม่ได้" ใช้ร่วมกัน (4 ที่)
 * ★ เทสที่ระดับนี้เพราะกฎเป็นฟังก์ชันบริสุทธิ์ — เคสขอบอ่านง่ายกว่าไปวัดผ่าน service
 */
const d = (s: string) => new Date(`2026-10-10T${s}:00Z`);

describe('timesOverlap', () => {
    it.each([
        ['ซ้อนกันบางส่วน',        '10:00', '11:30', '11:00', '12:00', true ],
        ['อันหนึ่งอยู่ในอีกอัน',   '10:00', '14:00', '11:00', '12:00', true ],
        ['เริ่มพร้อมกัน',          '10:00', '11:00', '10:00', '10:30', true ],
        ['จบพอดีแล้วเริ่มต่อ',     '10:00', '11:00', '11:00', '12:00', false],
        ['คนละช่วงไปเลย',         '10:00', '11:00', '13:00', '14:00', false],
    ])('%s', (_name, aStart, aEnd, bStart, bEnd, expected) => {
        expect(timesOverlap(d(aStart), d(aEnd), d(bStart), d(bEnd))).toBe(expected);
    });

    /** ★ ต้องตอบเหมือนกันไม่ว่าสลับลำดับ — ผู้เรียกบางที่วนเทียบทีละคู่โดยไม่เรียงก่อน */
    it('สลับฝั่งแล้วได้คำตอบเดิม', () => {
        expect(timesOverlap(d('11:00'), d('12:00'), d('10:00'), d('11:30'))).toBe(true);
        expect(timesOverlap(d('11:00'), d('12:00'), d('10:00'), d('11:00'))).toBe(false);
    });
});

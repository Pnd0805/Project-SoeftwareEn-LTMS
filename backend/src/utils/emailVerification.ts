import { env } from '../config/env.js';

/**
 * OD-53 (29 ต.ค. 2569) — SQL ที่ต่อท้าย WHERE เพื่อซ่อนบัญชีที่ยังไม่ยืนยันอีเมล
 *
 * ★ คืนค่าตามสวิตช์ `REQUIRE_EMAIL_VERIFIED` **ตัวเดียวกับด่านล็อกอิน** โดยเจตนา
 *   ถ้าซ่อนตลอดเวลาโดยไม่ดูสวิตช์ จะเกิดสภาพ "ล็อกอินได้แต่ไม่มีใครค้นเจอ"
 *   ⇒ ผู้ใช้ใช้งานได้ปกติแต่เพื่อนชวนเข้าทีมไม่ได้ และไม่มีข้อความอะไรอธิบายเลย
 *   ⇒ สองอย่างต้องเปิด/ปิดพร้อมกันเสมอ: เข้าระบบได้ = ถูกค้นเจอ
 *
 * ★ คืน '1' (จริงเสมอ) เมื่อสวิตช์ปิด เพื่อให้ผู้เรียกต่อสตริงได้โดยไม่ต้องมีเงื่อนไขซ้อน
 *   — แบบเดียวกับ notSuspendedSql ที่คืนสตริงพร้อมต่อ
 * 🔴 อ่าน env ตอนถูกเรียก ไม่ใช่ตอน import — เทสจะสลับค่าได้โดยไม่ต้องโหลดโมดูลใหม่
 */
export function emailVerifiedSql(alias : string) : string{
    return env.REQUIRE_EMAIL_VERIFIED ? `${alias}.email_verified = 1` : '1';
}

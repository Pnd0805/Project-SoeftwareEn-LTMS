import * as z from 'zod';

// C7 — Pick'em ทายผู้ชนะ (ทีมต้องอยู่ในแมตช์ — ตรวจใน service)
/**
 * OD-56 (4 ต.ค.) — ทายเป็น **สกอร์** ไม่ใช่ทายว่าทีมไหนชนะ
 *
 * ★ ไม่มี `teamId` อีกแล้ว — ผู้ชนะที่ทายคือฝั่งที่แต้มมากกว่า ระบบอนุมานให้เอง (มติข้อ ①)
 *   ให้ผู้ใช้ส่งทั้งสกอร์และผู้ชนะจะเปิดช่องให้สองอย่างขัดกันเอง แล้วต้องมีกฎว่าเชื่ออันไหน
 *
 * ★ key ต้องเป็นรหัสทีมสองทีมของแมตช์นั้น — ตรวจที่ service ไม่ใช่ที่นี่ เพราะ schema
 *   ไม่รู้ว่าแมตช์ไหนมีทีมอะไร (รูปแบบเดียวกับ ensureScoreData ของผลการแข่ง)
 *
 * ★ กันทายเสมอก็ตรวจที่ service — ระบบไม่รองรับผลเสมออยู่แล้ว ถ้าทายเท่ากัน
 *   จะอนุมานผู้ชนะไม่ได้ (มติข้อ ②)
 */
export const predictionSchema = z.object({
    scoreData: z.record(z.string(), z.int('คะแนนต้องเป็นจำนวนเต็ม').nonnegative('คะแนนต้องไม่ติดลบ') ,
                        'กรุณาทายคะแนนของทั้งสองทีม'),
});
export type PredictionInput = z.infer<typeof predictionSchema>;

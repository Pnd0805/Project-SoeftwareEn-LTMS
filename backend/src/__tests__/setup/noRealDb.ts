import { vi } from 'vitest';

/**
 * ด่านกันเทสไปต่อ MySQL จริง (OD-62, 4 ต.ค. 2569)
 *
 * ★ ทำไมต้องมี — เคสจริงที่เกิดแล้วเมื่อ 4 ต.ค.
 *
 * OD-58 ทำให้ `canSeeUnfinishedResult()` เรียก `adminScope.repo` เพิ่มขึ้นมาหนึ่งที่
 * แต่เทส 9 ไฟล์ที่เดินผ่านเส้นนั้น mock แค่ repo ที่ "เห็นว่าเกี่ยว" ⇒ repo ตัวใหม่ไม่ถูก mock
 * ⇒ เทสพวกนั้นไปต่อ MySQL ที่ `127.0.0.1:3307` จริง และ **ผ่าน** เพราะเครื่องมี docker รันอยู่
 *
 * ```
 * อาการคือ "เทสผ่าน" — ไม่ใช่ "เทสแดง"  ⇒ ไม่มีสัญญาณอะไรให้จับได้เลย
 * จับได้เพราะ docker ดับเองกลางทาง แล้วเทสที่ผ่านเมื่อครึ่งชั่วโมงก่อนกลายเป็น ECONNREFUSED
 * ```
 *
 * ของที่เสียไปไม่ใช่แค่ "เทสต้องมี docker" แต่คือ **เทสเลิกทดสอบสิ่งที่มันเขียนไว้ว่าทดสอบ**
 * — มันไปอ่านข้อมูลในฐานของเครื่องนั้น ⇒ ผลขึ้นกับว่าใครเพิ่ง seed อะไรไว้ ไม่ใช่ขึ้นกับโค้ด
 *
 * ★ ด่านนี้เปลี่ยน "ผ่านแบบพึ่งโชค" ให้เป็น "แดงทันทีพร้อมบอกว่าต้อง mock อะไร"
 *
 * วิธีทำงาน: mock `config/db.js` ให้เป็น pool ที่ระเบิดทุกเมธอด **เป็นค่าตั้งต้นของทุกไฟล์**
 * ไฟล์ที่ `vi.mock('.../config/db.js')` เองอยู่แล้ว (เทส repo ที่ตรวจตัว SQL) ทับอันนี้ได้ตามปกติ
 * เพราะ `vi.mock` ในไฟล์เทสถูกลงทะเบียนหลัง setup ⇒ ของในไฟล์ชนะ
 *
 * 🔴 ด่านนี้กันได้แค่ MySQL · S3/MinIO กับ SMTP ยังไม่มีด่าน (ดู OD-62)
 */

function blocked(method: string): never {
    throw new Error(
        `[no-real-db] เทสเรียก pool.${method}() = กำลังจะต่อ MySQL จริง\n` +
        `\n` +
        `สาเหตุที่พบบ่อยที่สุด: โค้ดที่เทสเรียกไป "แวะ repo ตัวใหม่" ที่ไฟล์นี้ยังไม่ได้ mock\n` +
        `(เช่นมีคนเพิ่ม repo call เข้า service/middleware ที่เทสนี้เดินผ่าน)\n` +
        `\n` +
        `ทางแก้ เลือกอย่างใดอย่างหนึ่ง:\n` +
        `  ① mock repo ตัวที่ขาด — ดู stack trace ว่าเป็นไฟล์ไหน แล้วใส่\n` +
        `       vi.mock('../../repositories/<ชื่อ>.repo.js', () => ({ <fn>: vi.fn(() => Promise.resolve(null)) }));\n` +
        `     ★ ใช้วิธีนี้เป็นหลัก เพราะเทสยังตรวจ "logic ของ service" ตามที่ตั้งใจไว้\n` +
        `  ② ถ้าไฟล์นี้ตั้งใจตรวจตัว SQL เอง ให้ mock pool ในไฟล์เทสเลย\n` +
        `       const mocks = vi.hoisted(() => ({ query: vi.fn() }));\n` +
        `       vi.mock('../../config/db.js', () => ({ default: { query: mocks.query } }));\n` +
        `\n` +
        `🔴 ห้ามแก้ด้วยการสั่งให้ docker รัน — นั่นคือรูเดิมที่ด่านนี้ตั้งมาปิด\n` +
        `   เทสที่อ่านฐานจริงจะให้ผลตามข้อมูลในเครื่องคนรัน ไม่ใช่ตามโค้ด`,
    );
}

vi.mock('../../config/db.js', () => ({
    default: {
        query: (): never => blocked('query'),
        execute: (): never => blocked('execute'),
        getConnection: (): never => blocked('getConnection'),
        end: (): never => blocked('end'),
    },
}));

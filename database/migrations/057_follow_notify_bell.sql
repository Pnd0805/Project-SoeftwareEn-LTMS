ALTER TABLE follows
  ADD COLUMN notify_enabled BOOLEAN NOT NULL DEFAULT FALSE
      COMMENT 'กระดิ่งรายคน · FALSE = ติดตามแต่ไม่รับแจ้งเตือน (ค่าตั้งต้นตามมติ 29 ต.ค.)';

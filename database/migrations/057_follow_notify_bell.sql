-- ทำไมต้องมี: เอกสารสัญญาว่าผู้ติดตามจะได้แจ้งเตือนเมื่อแมตช์ของนักกีฬาเริ่ม และเมื่อผลได้รับการยืนยัน
--   แต่การติดตามมีแค่ "ติดตาม / ไม่ติดตาม" ⇒ ต้องมีสวิตช์ต่อคู่ว่าอยากรับแจ้งเตือนจากคนนี้ไหม (แบบกระดิ่งยูทูป)
--
-- ★ DEFAULT FALSE ตามมติข้อ 1 — กดติดตามแล้วยังไม่รับแจ้งเตือน ต้องกดกระดิ่งเพิ่มเอง
--   ครอบแถวเดิมด้วย ⇒ ไม่ต้อง UPDATE เพิ่ม
--   🔴 ผลที่ตามมา: ลงแล้วจะยังไม่มีใครได้แจ้งเตือนเลยจนกว่า FE จะมีปุ่มกระดิ่ง
--      ฐาน dev/เดโมที่อยากลองยิงให้รัน `UPDATE follows SET notify_enabled = 1;` เอง — ไม่ใส่ในไฟล์นี้โดยเจตนา
-- ★ ห้ามเพิ่มคอลัมน์นี้ลง database/schema.sql — ทะเบียนในไฟล์นั้นหยุดที่ 036

-- ปัญหาที่แก้ (ไม่ใช่เรื่อง "กันกรอกเลขเว่อร์" อย่างเดียว):
--
--   ① หน่วยของสกอร์ไม่ได้ถูกกำหนดไว้ที่ไหนเลย
--      กฎที่มีอยู่จริงก่อนหน้านี้คือ key ต้องเป็นสองทีมของแมตช์ · ผู้ชนะต้องแต้มมากกว่า
--      ⇒ แบดมินตัน "2-0" (นับเกม) · "21-19" (แต้มในเกม) · "42-34" (รวมทุกเกม) ผ่านเท่ากันหมด
--      🔴 และ pickem ตั้ง tolerance ของแบด/RoV/VALORANT ไว้ (0,0) บนสมมติฐานว่าเป็นหน่วยเกม
--         ถ้ากรรมการกรอกเป็นแต้มในเกม คนที่ทายถูกจะกลายเป็น "ทายผิด" ทั้งทัวร์
--         โดยไม่มี error ไม่มี log ไม่มีใครรู้
--
--   ② ระบบ "เชื่อ" ว่าเป็น BO3 อยู่แล้ว แต่เป็นความเชื่อของคนเขียน migration ไม่ใช่ข้อมูล
--      migration 011 เขียนคอมเมนต์ไว้ว่า "แบดมินตัน 2–0 เกม" · "RoV BO3 2–0" · "VALORANT BO3 2–0 แมพ"
--      แต่ไม่มีอะไรบังคับ ⇒ ผู้จัดที่จัดรอบชิงเป็น BO5 จะได้ walkover 2-0 ซึ่งผิดรูปแบบ
--
-- ★ BO-N ไม่ได้แค่ "จำกัด" — มันกำหนดผลเกือบทั้งหมด:
--      ผู้ชนะต้องได้ (N+1)/2 เป๊ะ · ผู้แพ้ได้ 0 .. (N-1)/2
--      BO1 → 1 แบบ · BO3 → 2 แบบ (2-0, 2-1) · BO5 → 3 แบบ · BO7 → 4 แบบ
--   ⇒ ทั้งหน้าส่งผลและหน้าทายผลควรเป็น "ให้เลือก" ไม่ใช่ "ช่องกรอกเลข"
--
-- ═══ ทำไมเก็บเป็น INT ไม่ใช่ ENUM('BO1','BO3','BO5','BO7') ═══
-- ค่านี้ถูกเอาไป **คำนวณ** สองที่: จำนวนเกมที่ผู้ชนะต้องได้ = (N+1)/2 (ใช้ทั้งตอน validate
-- ผลการแข่งและตอนคิดสกอร์ walkover) ⇒ เก็บเป็นตัวเลขแล้วคิดตรง ๆ ดีกว่าแปลง 'BO7' → 7
-- ทุกครั้ง · ความปลอดภัยของค่าได้จาก CHECK ซึ่งแน่นเท่า ENUM
-- API ส่งออกเป็น bestOf: 3 แล้วให้ FE เรนเดอร์คำว่า "BO3" เอง
--
-- ═══ ทำไมเก็บสองที่ (ทัวร์ + แมตช์) ═══
-- `tournaments.best_of` = ค่าตั้งต้นที่ผู้จัดตั้งตอนสร้างทัวร์
-- `matches.best_of`     = ค่าที่ใช้จริงของแมตช์นั้น (stamp มาจากทัวร์ตอนสร้างสาย)
-- เพราะของจริงรอบแบ่งกลุ่มกับรอบชิงมักไม่เหมือนกัน (กลุ่ม BO3 · ชิง BO5)
-- ถ้าเก็บที่ทัวร์อย่างเดียวจะบังคับให้ทั้งทัวร์เป็นรูปแบบเดียว ซึ่งไม่ตรงความจริง
-- 🔴 แหล่งความจริงของการคิดแต้ม/ตรวจสกอร์คือ `matches.best_of` เสมอ ไม่ใช่ของทัวร์
--
-- ═══ NULL หมายถึงอะไร (มติข้อ ①) ═══
-- NULL = กีฬานี้ไม่ได้แข่งเป็นรอบ ⇒ ไม่มีเพดาน ใช้กฎเดิมทั้งหมด
-- ฟุตบอลและบาสเกตบอลเป็น NULL โดยเจตนา — สกอร์คือประตู/แต้มในเกมเดียว
-- ═══════════════════════════════════════════════════════════════════════════════

SET NAMES utf8mb4;

ALTER TABLE tournaments
  ADD COLUMN best_of INT NULL AFTER bracket_format,
  ADD CONSTRAINT chk_tournaments_best_of CHECK (best_of IS NULL OR best_of IN (1, 3, 5, 7));

ALTER TABLE matches
  ADD COLUMN best_of INT NULL AFTER round_number,
  ADD CONSTRAINT chk_matches_best_of CHECK (best_of IS NULL OR best_of IN (1, 3, 5, 7));

-- ═══ backfill — ตั้งใจไม่เดาค่าให้ของเก่า (มติ 5 ต.ค. หลังตรวจฐานจริง) ═══
--
-- ตอนตั้งคำถามเรื่องนี้ ประเด็นคือ "แถวเก่าที่สกอร์ไม่เข้ารูปแบบจะทำยังไง"
-- ตรวจฐานจริง (ltms, 5 ต.ค.) แล้วได้: ทัวร์ 2 · แมตช์ 7 · ผลการแข่ง 3 · pickem 0
-- และ **ทั้ง 7 แมตช์เป็นฟุตบอล** ซึ่งมติข้อ ① บอกว่าเป็น NULL
-- ⇒ ไม่มีแถวไหนไม่เข้ารูปแบบเลยแม้แถวเดียว ⇒ ไม่มีอะไรให้ backfill
--
-- 🔴 และการ "เดา" ว่าทัวร์เก่าของกีฬาที่แข่งเป็นรอบคือ BO3 เป็นของที่เสียมากกว่าได้:
--   เดาผิด (ทัวร์นั้นจัด BO5) ⇒ แมตช์ที่ยังไม่แข่งถูกบังคับรูปแบบ BO3 ทันที
--   ⇒ กรรมการที่กำลังจะส่งผล 3-1 ซึ่งถูกต้องสำหรับ BO5 จะถูกปฏิเสธ
--   ⇒ ของที่เคยทำได้กลายเป็นทำไม่ได้ บนเครื่องของคนอื่นที่เราไม่เห็นข้อมูล
--
-- ส่วน NULL = ไม่มีเพดาน = กฎเดิมทุกข้อ ⇒ ไม่มีอะไรพังเพิ่ม
-- และมติข้อ ⑤ บังคับให้ผู้จัดตั้ง format ก่อนแมตช์แรกเริ่มแข่งอยู่แล้ว
-- ⇒ ทัวร์เก่าที่ยังไม่เริ่ม ผู้จัดตั้งเองได้ · ทัวร์ที่เริ่มไปแล้วก็ไม่ควรถูกบังคับย้อนหลัง
--
-- ★ บทเรียนจากตอนเขียนร่างแรกของไฟล์นี้: ร่างแรกเดา BO3 โดยอ้างกีฬาด้วย **ชื่อ**
--   ('RoV' , 'VALORANT') ซึ่งชื่อจริงในฐานคือ 'E-Sport: RoV' , 'E-Sport: VALORANT'
--   ⇒ UPDATE ไม่แมตช์เลย และ **ไม่มี error** เพราะ UPDATE 0 แถวไม่ใช่ความผิดพลาดสำหรับ MySQL
--   🔴 ห้ามอ้างกีฬาด้วยชื่อใน migration ต่อ ๆ ไป — ถ้าจำเป็นให้ตรวจผลด้วย SELECT หลัง UPDATE
--     (migration 040 รอดเพราะตั้งชื่อแค่ 'ฟุตบอล'/'บาสเกตบอล' ที่ตรงเป๊ะ ไม่ใช่เพราะระวัง)
--

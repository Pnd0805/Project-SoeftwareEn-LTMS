-- 🔴 วันตัดฝังตายตัว ไม่ใช่ "ทุกแถวที่มีอยู่ตอนรัน" โดยเจตนา
--   migration รันครั้งเดียวต่อเครื่อง และแต่ละคน pull + migrate คนละเวลา
--   ถ้าเขียนว่า `WHERE email_verified = 0` เฉย ๆ ความหมายจะกลายเป็น
--   "ปลดล็อกทุกแถวที่มีอยู่ ณ วินาทีที่เครื่องนั้นรัน" ⇒ แต่ละเครื่องได้คนละชุด
--     · คนที่สมัครบัญชีทดสอบ **ก่อน** รัน migrate จะได้บัตรผ่านฟรีโดยไม่มีใครรู้
--     · ผลต่างกันทุกเครื่องทั้งที่โค้ดชุดเดียวกัน ⇒ ทำซ้ำไม่ได้ เถียงกันว่าใครถูก
--     · และตัวรัน migration จำชื่อไฟล์ว่ารันแล้ว ⇒ **รันซ้ำแก้ทีหลังไม่ได้** ยกเว้นถาวร
--   ⇒ ฝังวันตัดไว้ในไฟล์ ทุกเครื่องจึงปลดล็อก "ชุดเดียวกันทางตรรกะ" ไม่ว่าจะรันเมื่อไร
--
-- ★ วันตัด = วันที่ตั้งใจเปิดด่านจริง (30 ต.ค. 2569 00:00 เวลาไทย)

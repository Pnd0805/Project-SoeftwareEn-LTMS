-- =====================================================================
-- 052 — user_type: 'staff' = คนที่มียศแอดมิน/root เท่านั้น (มติ 8 ต.ค. 2569)
-- =====================================================================
--
-- ก่อนหน้านี้ `'staff'` เป็นค่า **ร้าง**: ไม่มีโค้ดบรรทัดไหนเขียนมัน (ตั้งแต่มติ 6 ต.ค.
-- ที่ให้ `auth.service` คิด user_type จากโดเมนอีเมล) และไม่มีโค้ดไหนอ่านมันไปตัดสินอะไรเลย
-- มีแต่แถวใน seed ที่ค้างค่านี้ไว้ ⇒ ค่าที่ไปถึงไม่ได้และไม่มีความหมาย
--
-- มติใหม่: ให้ `'staff'` หมายถึง **"คนที่ถือยศ"** — ได้ตอนแต่งตั้ง และกลับเป็นค่าตามอีเมลตอนถอดยศ
--   ⇒ คอลัมน์นี้กลับมามีความหมายและไปถึงได้จริง โดยไม่ต้องแก้ ENUM
--
-- 🔴 ไฟล์นี้ทำให้ **ข้อมูลเดิมตรงกับกฎใหม่** (ไม่ใช่แค่โค้ดใหม่ถูก แต่ข้อมูลเก่าผิด)
--   ① ใครมีแถวใน `admin_scopes` (รวม root) ⇒ 'staff'
--   ② คนอื่นทั้งหมด ⇒ คิดจากโดเมนอีเมลด้วยกฎเดียวกับ `utils/kuEmail.ts`
--      @ku.th → 'student' · โดเมนอื่น → 'external'
--
-- ★ ข้อ ② เขียนทับทุกแถวที่ไม่ใช่แอดมินโดยเจตนา ไม่ได้แตะแค่ 'staff'
--   เพราะมีที่เดียวในระบบที่เขียนคอลัมน์นี้ (ตอนสมัคร คิดจากอีเมล) ⇒ ค่าที่ถูกต้องคำนวณได้เสมอ
--   ถ้าแถวไหนไม่ตรง แปลว่าเป็นข้อมูลที่ค้างมาจากก่อนมติ 6 ต.ค. ไม่ใช่ความตั้งใจของใคร
--   ผลที่เกิดกับ seed ปัจจุบัน: **กรรมการ 9051 · 9052** เปลี่ยนจาก 'staff' → 'student'
--   (เป็น @ku.th และไม่มีแถวใน admin_scopes)
--   คง 'staff' ไว้: 9001 (university_wide) · 9004 (faculty คณะ 1) · 9099 (root) — ทั้งสามมีแถวจริง
--   ★ ไฟล์ seed ทั้ง 4 ถูกแก้ให้ตรงกับกฎนี้แล้วในคอมมิตเดียวกัน
--     ⇒ ฐานที่สร้างใหม่จะถูกต้องตั้งแต่ต้น ไม่ต้องพึ่ง migration นี้
--
-- ★ เทียบโดเมนด้วย SUBSTRING_INDEX(email,'@',-1) ไม่ใช่ LIKE '%ku.th'
--   เหตุผลเดียวกับที่ `kuEmail.ts` ไม่ใช้ endsWith: `fake-ku.th` กับ `notku.th` จะผ่านด้วย
--
-- 🙋 ENUM ไม่ถูกแก้ — ยังเป็น ('student','staff','external') เหมือนเดิม
--   (เคยคุยว่าจะลบ 'staff' ทิ้ง · มตินี้แทนอันนั้น เพราะค่านี้มีงานทำแล้ว)
-- =====================================================================

-- ① คนที่ถือยศ
UPDATE users u
   SET u.user_type = 'staff'
 WHERE EXISTS (SELECT 1 FROM admin_scopes s WHERE s.user_id = u.user_id);

-- ② ทุกคนที่เหลือ — คิดจากโดเมนอีเมล (กฎเดียวกับ utils/kuEmail.ts)
UPDATE users u
   SET u.user_type = CASE
         WHEN LOWER(TRIM(SUBSTRING_INDEX(u.email , '@' , -1))) = 'ku.th' THEN 'student'
         ELSE 'external'
       END
 WHERE NOT EXISTS (SELECT 1 FROM admin_scopes s WHERE s.user_id = u.user_id);

SET NAMES utf8mb4;

ALTER TABLE sport_types
  ADD COLUMN supports_best_of TINYINT(1) NOT NULL DEFAULT 0 AFTER default_mode;

-- ═══ ค่าของกีฬาที่มีอยู่ ═══
-- ไม่ได้คิดใหม่ — ใช้ตามที่ seed.sql เขียนกำกับไว้เองตั้งแต่ต้น
--   ฟุตบอล (FIFA 3–0) · บาสเกตบอล (FIBA 20–0)      → นับแต้มในเกมเดียว   = 0
--   แบดมินตัน (2–0 เกม) · RoV (BO3) · VALORANT (BO3 แมพ) → นับเกม/แมพ      = 1
--
-- 🔴 จับจาก **ชื่อ** ไม่ใช่ id — ฐานที่ใครตั้งด้วยมือ id อาจไม่ตรงกับ seed
--   แถวที่ชื่อไม่ตรงรายการนี้จะคงค่า 0 ไว้ (ต้องมีคนไปเปิดให้เองถ้าเป็นกีฬาที่แข่งเป็นรอบ)
UPDATE sport_types
   SET supports_best_of = 1
 WHERE name IN ('แบดมินตัน', 'E-Sport: RoV', 'E-Sport: VALORANT');


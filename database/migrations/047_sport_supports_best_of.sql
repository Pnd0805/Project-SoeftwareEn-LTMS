--
-- ★ DEFAULT 0 = "ไม่ได้แข่งเป็นรอบ" สำหรับกีฬาที่เพิ่มใหม่ในอนาคต
--   เลือกทางที่เข้มกว่าโดยเจตนา: กีฬาใหม่จะตั้ง BO ไม่ได้จนมีคนตั้งใจเปิดให้
--   (ด่านที่แอป — ดู utils/matchFormat.bestOfNotSupportedError) ⇒ ลืมแล้วเห็นเป็น 400 ไม่ใช่ข้อมูลเพี้ยนเงียบ ๆ

-- ไฟล์นี้รองรับส่วนที่ 2: **แจ้งล่วงหน้า** ซึ่งต้องจำว่า "เตือนทัวร์นี้ไปแล้ว"
--
-- 🔴 ทำไมต้องมีคอลัมน์ ไม่ใช่คำนวณสด
--   งานเบื้องหลังรันทุกชั่วโมง (มติ 8 ต.ค.) ⇒ ถ้าไม่มีที่จำว่าเตือนแล้ว
--   ผู้จัดจะได้ข้อความเดิม **24 ครั้งต่อวัน** ตลอด 7 วัน = 168 ครั้งต่อทัวร์
--   ★ ทางเลือกที่ไม่ต้อง migration คือไปค้นตาราง `notifications` ว่าเคยส่งหรือยัง
--     แต่นั่นคือการผูกตรรกะธุรกิจไว้กับ **ประวัติแจ้งเตือน** ซึ่งเป็นข้อมูลที่ลบได้/ล้างได้
--     ⇒ วันที่ใครล้างแจ้งเตือนเก่า ผู้จัดจะถูกเตือนซ้ำทั้งหมด (มติ 8 ต.ค. เลือกทาง ก)
--
-- ★ เก็บเป็น "เวลาที่เตือน" ไม่ใช่ธงบูลีน — ตอบคำถามได้มากกว่าด้วยพื้นที่เท่ากัน
--   (เตือนไปเมื่อไร · เตือนทันไหม · เผื่อวันที่อยากเปลี่ยนจาก 7 วันเป็นเลขอื่น)
--
-- ★ ไม่ตั้งค่าให้แถวเดิม (ปล่อย NULL) โดยเจตนา
--   NULL = ยังไม่เคยเตือน ⇒ ทัวร์ private ที่ใกล้ถึงวันแข่งอยู่แล้วตอนนี้จะได้รับการเตือน
--   ในรอบงานถัดไป ซึ่งคือเจตนา — ไม่ใช่ปล่อยให้ถูกปิดเงียบ ๆ โดยไม่มีใครบอก

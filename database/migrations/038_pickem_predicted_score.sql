-- OD-56 (4 ต.ค. 2569) — Pick'em เปลี่ยนจาก "ทายว่าทีมไหนชนะ" เป็น "ทายสกอร์"
--
-- ที่มา: อยากให้คนที่ทายใกล้เคียงได้คะแนนด้วย แต่ของเดิมเก็บแค่ predicted_winner_team_id
-- ซึ่งเป็นค่าสองทาง ⇒ **ไม่มีคำว่า "ใกล้เคียง" อยู่ในข้อมูลเลย** ทายถูกหรือผิดเท่านั้น
-- จะคิดคะแนนบางส่วนได้ต้องเก็บสกอร์ที่ทายก่อน
--
-- ═══ ผู้ชนะที่ทาย = ระบบอนุมานจากสกอร์ ไม่ใช่ให้ผู้ใช้เลือกแยก (มติข้อ ① 4 ต.ค.) ═══
-- `predicted_winner_team_id` **ยังอยู่และยังเป็น NOT NULL** แต่เปลี่ยนที่มา: service คำนวณจาก
-- สกอร์ที่ทาย (ฝั่งที่แต้มมากกว่า) แล้วเขียนลงไป ไม่ได้รับมาจาก request อีกแล้ว
--
-- ทำไมไม่ลบคอลัมน์นั้นทิ้งแล้วคำนวณสด ๆ ตอน query:
--   1. settleTx / unsettleTx / E27 / E28 / E29 อ่านคอลัมน์นี้อยู่ทั้งหมด — ลบคือรื้อ 5 ที่
--   2. SQL ที่ต้อง "หาว่า JSON ฝั่งไหนมากกว่า" ทุกครั้งที่อ่าน จะช้าและอ่านยากกว่ามาก
--   3. การเก็บผลการอนุมานไว้ทำให้ย้อนดูได้ว่าตอนนั้นระบบตีความว่าอะไร
-- ⇒ ถือว่าเป็น derived column ที่ materialize ไว้ ไม่ใช่ข้อมูลซ้ำซ้อน
--
-- ═══ NULL ได้ ไม่ใช่ NOT NULL (มติข้อ ② 4 ต.ค.) ═══
-- ฐานของผมมี 0 แถว แต่เครื่องเพื่อนอาจมีการทายค้างอยู่จากที่เทสกันไว้
-- ถ้าใส่ NOT NULL แล้วไม่มี default (JSON ใส่ default ตรง ๆ ไม่ได้ใน MySQL 8 ต้องใช้ expression)
-- migration จะล้มบนเครื่องพวกนั้นทันที
--
-- ⇒ **NULL = แถวที่ทายไว้ก่อน migration นี้** · ตอนคิดคะแนนให้ถือว่า "ทายแค่ฝั่ง"
--    ได้คะแนนพื้นถ้าฝั่งถูก ไม่มีสิทธิ์ได้โบนัสสกอร์ (ไม่มีสกอร์ให้เทียบ)
--    ของใหม่ที่ส่งเข้ามาหลังจากนี้ **บังคับมีสกอร์** ด่านอยู่ที่ schema ไม่ใช่ที่ฐาน
--
-- ═══ JSON ไม่ใช่สองคอลัมน์ score_a / score_b ═══
-- ให้รูปร่างตรงกับ `match_results.score_data` ซึ่งเป็น `{"<teamId>": n}` อยู่แล้ว
-- ⇒ ตอนคิดคะแนนเทียบกันได้ตรง ๆ ด้วย key เดียวกัน ไม่ต้องจำว่า a/b คือทีมไหน
--    (team_a_id/team_b_id สลับกันได้ตามสาย การผูกกับ a/b จะเปิดช่องให้เทียบผิดฝั่ง)
ALTER TABLE pickem_predictions
  ADD COLUMN predicted_score_data JSON NULL AFTER predicted_winner_team_id;

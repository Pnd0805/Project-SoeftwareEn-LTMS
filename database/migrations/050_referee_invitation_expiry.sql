-- 050 — คำเชิญกรรมการต้องมีวันหมดอายุ (BE-13 · มติ 7 ต.ค. 2569 ข้อ ⑨ ง)
-- =====================================================================
--
-- ปัญหา: ผู้จัดเชิญใครเป็นกรรมการ แล้วคนนั้นไม่ตอบ ⇒ **ทีมของคนนั้นสมัครทัวร์นั้นไม่ได้ตลอดไป**
--   เพราะด่าน Conflict of interest นับคำเชิญสถานะ 'pending' ว่าเป็นกรรมการแล้ว
--   และ `tournament_referees` ไม่มีคอลัมน์วันหมดอายุเลย ขณะที่คำเชิญเข้าทีม
--   (`team_invitations.expires_at`) มี 7 วันมาตั้งแต่ migration 013
--
-- 🔴 ทำไมถึงเป็นเรื่องใหญ่กว่าที่เห็น — 409 ไปโผล่ที่ **หัวหน้าทีม**
--   ซึ่งไม่มีสิทธิ์ทั้งสองทางที่ปลดล็อกได้ (ผู้ถูกเชิญกดปฏิเสธ / ผู้จัดยกเลิกคำเชิญ)
--   ส่วนสองคนที่กดได้ ไม่มีใครรู้เลยว่ากำลังบล็อกใครอยู่
--   ⇒ ข้อมูลอยู่คนละมือกับคนที่กดแก้ได้ · และถ้าผู้จัดหายไปจากโครงการ = ตันถาวร
--
-- ★ เลือก "7 วัน" ให้ตรงกับคำเชิญเข้าทีม (มติ ⑨ ง) — อธิบายผู้ใช้ได้ในประโยคเดียว
--   และมีแบบอย่างในระบบอยู่แล้ว ไม่ต้องสร้างกฎใหม่ให้จำเพิ่ม
-- ★ ไม่เพิ่มค่า 'expired' เข้า ENUM `invitation_status` โดยเจตนา —
--   ① คอลัมน์นั้นถูกอ้างในนิพจน์ของ generated column `active_user_id` (migration 036)
--      การ MODIFY ชนิดของมันจึงเป็นความเสี่ยงที่ไม่จำเป็น
--   ② ระบบไม่มี scheduler ⇒ ต่อให้มีค่า 'expired' ก็ไม่มีใครไปเขียนให้อยู่ดี
--   ⇒ ใช้วิธีเดียวกับ `team_invitations`: เก็บ **เวลา** แล้วให้ทุก query เทียบกับ NOW()
--      สถานะ "หมดอายุ" จึงเป็นสิ่งที่คำนวณได้เสมอ ไม่ใช่สิ่งที่ต้องมีคนไปเขียน
--
-- 🙋 ข้อมูลเดิม — **ตัดสินใจเอง บอกไว้ตรงนี้**
--   แถว pending ที่มีอยู่ตอนนี้ไม่มีวันหมดอายุ ⇒ ต้องเลือกว่าจะนับจากอะไร
--   เลือก `created_at + 7 วัน` (ไม่ใช่ `NOW() + 7 วัน`) เพราะ
--     ① เป็นกติกาเดียวกับที่คำเชิญใหม่จะได้ ⇒ ไม่มีสองมาตรฐาน
--     ② คำเชิญที่ค้างมานานกว่า 7 วันคือ "เคสที่ BE-13 รายงาน" พอดี — ควรหลุดล็อกทันที
--        ไม่ใช่ต่ออายุให้อีก 7 วันทั้งที่ค้างมาเป็นเดือน
--   ⇒ หลัง migration นี้ คำเชิญเก่าที่ไม่มีใครตอบจะเลิกบล็อกทีมทันที ซึ่งคือเจตนา
-- =====================================================================

ALTER TABLE tournament_referees
  ADD COLUMN expires_at DATETIME NULL
      COMMENT 'คำเชิญหมดอายุเมื่อไหร่ (เฉพาะแถวที่ยัง pending) — NULL = ไม่มีวันหมดอายุ';

UPDATE tournament_referees
   SET expires_at = created_at + INTERVAL 7 DAY
 WHERE invitation_status = 'pending'
   AND removed_at IS NULL
   AND expires_at IS NULL;

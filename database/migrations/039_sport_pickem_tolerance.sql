-- OD-56 ก้าวที่ 2 (4 ต.ค. 2569) — โบนัสสกอร์ของ Pick'em ต้องรู้จักสเกลของกีฬา
--
-- ═══ ปัญหาที่คอลัมน์นี้แก้ ═══
-- 5 กีฬาในระบบนับสกอร์คนละหน่วย และ `walkover_score` บอกไว้อยู่แล้วโดยที่ยังไม่มีใครใช้:
--
--   ฟุตบอล      3-0     นับ "แต้มจริง" (ประตู)          ช่วงจริง 0–5
--   บาสเกตบอล   20-0    นับ "แต้มจริง"                  ช่วงจริง 50–120
--   แบดมินตัน   2-0     นับ "เกมที่ชนะ" (ชนะ 2 ใน 3)    ช่วงจริง 0–2
--   RoV         2-0     นับ "เกมที่ชนะ" (Bo3/Bo5)       ช่วงจริง 0–2
--   VALORANT    2-0     นับ "แมปที่ชนะ" (Bo1/Bo3)       ช่วงจริง 0–2
--
-- ⇒ ถ้าให้โบนัส "ทายสกอร์เป๊ะ" ด้วยกฎเดียวกันหมด ความยากต่างกันคนละโลก:
--     แบด/RoV/VALORANT  ทายฝั่งถูกแล้วเหลือ 2 ทางเลือก (2-0 / 2-1)  →  ลุ้นได้ ~50%
--     ฟุตบอล            สกอร์ที่เจอจริงราว ๆ 10 แบบ                →  ~10-20%
--     บาสเกตบอล         98-95 ต้องเป๊ะทั้งสองตัว                    →  **แทบ 0%**
--   = โบนัสแจกตามกีฬา ไม่ใช่ตามฝีมือ
--
-- ★ และในกีฬาที่นับเป็นเกม ชั้น "ผลต่างตรง" **ซ้ำกับชั้นสกอร์เป๊ะ 100%**
--   Bo3 ผู้ชนะต้องได้ 2 เกม ⇒ สกอร์ที่เป็นไปได้มีแค่ 2-0 (ผลต่าง 2) กับ 2-1 (ผลต่าง 1)
--   รู้ว่าใครชนะ + รู้ผลต่าง = รู้สกอร์เป๊ะทันที ⇒ ชั้นนั้นไม่ให้คะแนนใครเพิ่มเลยใน 3 จาก 5 กีฬา
--   จึงเปลี่ยนชั้นกลางจาก "ผลต่างตรง" เป็น "คลาดรวมไม่เกิน tolerance ของกีฬานั้น"
--
-- ═══ ทำไมคอลัมน์ใหม่ ไม่ใช้ walkover_score เป็นตัวบอกสเกล ═══
-- `walkover_score` พอใช้ได้ (3 / 20 / 2) แต่ความหมายของมันคือ "สกอร์ที่ให้เมื่อปรับแพ้บาย"
-- ถ้าเอามาคิดโบนัส pick'em ด้วย วันหนึ่งมีคนแก้สกอร์บายของบาสจาก 20-0 เป็น 2-0
-- โบนัส pick'em จะเปลี่ยนตามไปโดยไม่มีใครรู้ว่าแตะอะไรไป
-- ⇒ คอลัมน์ที่มีความหมายเดียวชัดเจน ดีกว่าคอลัมน์ที่ถูกอ่านสองความหมาย
--
-- DEFAULT 0 = "ต้องเป๊ะ" — ปลอดภัยที่สุดสำหรับกีฬาใหม่ที่ยังไม่มีใครตั้งค่า
-- (ให้โบนัสยากเกินไปแก้ง่ายกว่าแจกโบนัสฟรีแล้วค่อยรู้ตัว)
ALTER TABLE sport_types
  ADD COLUMN pickem_score_tolerance INT NOT NULL DEFAULT 0 AFTER walkover_score;

-- ค่าเริ่มต้นต่อกีฬา — อิงหน่วยที่สากลใช้ ไม่ใช่ตัวเลขสุ่ม
--   แบด/RoV/VALORANT = 0  ชั้นกลางไม่ยิง **โดยเจตนา** เพราะชั้นเป๊ะง่ายอยู่แล้ว (เหลือ 2 ทางเลือก)
--   ฟุตบอล          = 1  ทาย 2-1 ได้จริง 3-1 หรือ 2-0 ก็ยังได้โบนัสกลาง
--   บาสเกตบอล       = 5  ทาย 95-90 ได้จริง 98-90 ก็ยังได้ — ทำให้บาสมีสิทธิ์ได้โบนัสจริง
UPDATE sport_types SET pickem_score_tolerance = 1 WHERE name = 'ฟุตบอล';
UPDATE sport_types SET pickem_score_tolerance = 5 WHERE name = 'บาสเกตบอล';

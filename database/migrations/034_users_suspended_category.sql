-- มติ 1 ต.ค. 2569 (OD-40 ทางเลือก ข) — บอกคนที่ถูกระงับว่า "ประเภทไหน" ไม่ส่งข้อความดิบที่แอดมินพิมพ์
--
-- suspended_reason ถูกบังคับให้แอดมินกรอกและเก็บไว้ แต่คนที่ถูกระงับไม่เคยเห็น และไม่มีทางเห็นทางอื่น
-- (โดน 403 ทุกเส้น เปิดกล่องแจ้งเตือนไม่ได้) ⇒ ถ้าไม่ฝากมากับ error ก็คือไม่บอกเลย
--
-- แต่จะส่ง suspended_reason ดิบออกไปไม่ได้ เพราะตอนแอดมินพิมพ์ ช่องนั้นเขียนไว้ให้แอดมินคนถัดไปอ่าน
-- ไม่ได้เขียนให้คู่กรณีอ่าน · การเปลี่ยนใจส่งออกทีหลังคือการเปลี่ยนความหมายของข้อมูลที่เก็บมาแล้วย้อนหลัง
--
-- ⇒ แยกเป็นสองช่อง: suspended_reason = บันทึกภายในของแอดมิน (เหมือนเดิม ไม่ส่งออก)
--                   suspended_category = ประเภทที่ส่งให้เจ้าตัวเห็น เลือกจากชุดปิดที่เขียนถ้อยคำไว้แล้ว
--
-- NULL = ไม่ได้ระบุ ⇒ 403 ตอบข้อความกลาง ๆ เหมือนก่อน migration นี้
-- แถวเก่าทุกแถวเป็น NULL จึงไม่มีแถวไหนเปลี่ยนความหมาย และ API ใหม่บังคับกรอกตอนระงับ
--
-- ENUM ไม่ใช่ VARCHAR เพราะชุดนี้เป็นชุดปิดเหมือน user_report_status — ฐานควรปฏิเสธค่าที่ไม่รู้จัก
-- ไม่ใช่ปล่อยให้ schema ชั้น API เป็นด่านเดียว · เพิ่มประเภทใหม่ = migration ใหม่ ซึ่งถูกแล้ว
-- เพราะการเพิ่มประเภทต้องมาพร้อมถ้อยคำไทยที่ผู้ใช้จะอ่าน ไม่ใช่เพิ่มคีย์ลอย ๆ
ALTER TABLE users
  ADD COLUMN suspended_category ENUM('abusive_language','cheating','false_information','spam','other') NULL AFTER suspended_reason;

-- FR09 — กรรมการขอถอนตัว (ref_withdraw) · มติ 6 ต.ค. 2569 (ทางเลือก ซ · ขอบเขตแบบ ญ3)
-- ═══════════════════════════════════════════════════════════════════════════════
--
-- ปัญหาที่แก้: ตารางอำนาจเรื่องกรรมการมีช่องว่างอยู่หนึ่งช่อง
--
--   ORG ขอเพิ่มแมตช์ให้กรรมการ        org_add_match   มี
--   ORG สลับกรรมการสองคน              org_swap        มี
--   กรรมการโอน/แลกกันเอง              ref_transfer · ref_swap   มี
--   🔴 กรรมการขอ "ออก" โดยให้ ORG ตัดสิน            ไม่มี
--
-- วันนี้กรรมการที่ตอบรับไปแล้วออกได้ทางเดียวคือ ref_transfer/ref_swap ซึ่ง
-- **ต้องมีกรรมการอีกคนมารับช่วงและกดรับ** ⇒ ถ้าทัวร์นั้นไม่มีคนอื่น หรือมีแต่ไม่มีใครรับ
-- เขาไม่มีทางออกในระบบเลย ต้องไปตามตัว ORG นอกระบบ
-- และถ้าเขาถูกเชิญแบบ pool (ยังไม่ได้รับแมตช์ไหน) จะไม่มีใบให้ยื่นด้วยซ้ำ
-- ⇒ อยู่ในทัวร์ ถูกนับใน acceptedCount แต่ออกไม่ได้
--
-- ★ ทำไมให้ ORG เป็นคนอนุมัติ ไม่ใช่ให้กรรมการถอนตัวเองได้เลย
--   ORG เป็นคนที่ต้องรับผลของการขาดกรรมการ และวันนี้เขามีอำนาจถอดอยู่แล้ว (F03)
--   สิ่งที่ขาดคือ "ช่องทางให้กรรมการขอ" ไม่ใช่อำนาจใหม่
--   ถ้าให้ถอนเองได้ ref_transfer จะเกือบไร้ความหมาย — ไม่มีใครเสียเวลาหาคนรับช่วงอีก
--
-- ═══ สองขอบเขตในใบเดียว (มติ ญ3) ═══
-- withdraw_scope = 'match'       ออกจากแมตช์เดียว  ⇒ match_a_id ต้องมีค่า
-- withdraw_scope = 'tournament'  ออกจากทัวร์ทั้งทัวร์ ⇒ match_a_id เป็น NULL
--
-- 🔴 เหตุที่ต้องมีสองขอบเขต: การทับเวลาข้ามทัวร์แก้ด้วยการออกจาก **แมตช์เดียว** พอ
--   (ทิ้งทัวร์ทั้งทัวร์เพื่อแก้การทับ 30 นาที = เยียวยาแรงเกินเหตุ ORG เสียคนทั้งคนฟรี)
--   แต่เหตุอย่างป่วย/ลาออก/รับไว้มากเกินไป ต้องออกทั้งทัวร์
--   ถ้ามีแต่ขอบเขตแมตช์ เขาจะต้องยื่น N ใบ และ ORG ต้องกด N ครั้ง
-- ═══════════════════════════════════════════════════════════════════════════════

SET NAMES utf8mb4;

-- ① ชนิดใหม่
ALTER TABLE referee_change_requests
  MODIFY request_type ENUM('org_add_match','ref_transfer','ref_swap','org_swap','ref_withdraw') NOT NULL;

-- ② match_a_id ต้องยอมให้เป็น NULL ได้ เพราะใบระดับทัวร์ไม่ได้อ้างแมตช์ไหน
--
-- 🔴 นี่คือการ **คลาย** ข้อบังคับที่เคยแน่น ⇒ เติม CHECK กลับไปทันทีในข้อ ④
--   ไม่ปล่อยให้สี่ชนิดเดิมกลายเป็นชนิดที่ match_a_id ว่างได้ เพราะทั้งสี่อ้างแมตช์เสมอ
ALTER TABLE referee_change_requests
  MODIFY match_a_id INT NULL;

-- ③ ขอบเขต + เหตุผล
--
-- ★ เหตุผล **บังคับ** สำหรับ ref_withdraw (ด่านอยู่ที่แอป · คอลัมน์เป็น NULL ได้เพราะ
--   สี่ชนิดเดิมไม่มีเหตุผลและไม่ควรถูกบังคับย้อนหลัง)
--   เหตุ: ORG ตัดสินใจไม่ได้เลยถ้าไม่รู้ว่าเพราะอะไร — "ติดทัวร์อื่นเวลาทับ" กับ "ไม่อยากคุมแล้ว"
--   ควรได้คำตอบต่างกัน และ ORG คือคนที่ต้องไปหาคนแทน
ALTER TABLE referee_change_requests
  ADD COLUMN withdraw_scope ENUM('match','tournament') NULL AFTER request_type,
  ADD COLUMN request_reason TEXT NULL AFTER b_status;

-- ④ ความสอดคล้องของทั้งสองคอลัมน์ใหม่ กับชนิดของใบ
ALTER TABLE referee_change_requests
  ADD CONSTRAINT chk_rcr_withdraw_shape CHECK (
    (request_type <> 'ref_withdraw' AND withdraw_scope IS NULL AND match_a_id IS NOT NULL)
    OR (request_type = 'ref_withdraw' AND withdraw_scope = 'match'      AND match_a_id IS NOT NULL)
    OR (request_type = 'ref_withdraw' AND withdraw_scope = 'tournament' AND match_a_id IS NULL)
  );

-- ═══ ไม่มี backfill — ของเก่าทุกแถวเป็นสี่ชนิดเดิม ⇒ withdraw_scope NULL ถูกต้องอยู่แล้ว ═══
-- และ CHECK ข้างบนบังคับว่าแถวเก่าต้องมี match_a_id ซึ่งเป็นจริงทุกแถวเพราะคอลัมน์เคยเป็น NOT NULL
-- 🔴 ถ้า ALTER ข้อ ④ พัง แปลว่ามีแถวที่ไม่เข้ารูปแบบอยู่ก่อนแล้ว — อย่าถอด CHECK ออกเพื่อให้ผ่าน
--   ให้ SELECT หาแถวนั้นก่อน (บทเรียนจาก migration 044: UPDATE ที่แมตช์ 0 แถวไม่ใช่ error)

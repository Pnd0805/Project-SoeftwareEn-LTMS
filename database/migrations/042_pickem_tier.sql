-- OD-65 — เก็บ "ชั้น" ของใบทายเป็นคอลัมน์ ไม่ใช่เดาย้อนจากแต้ม
--
-- เดิม pickem_predictions เก็บแต่ points_earned ⇒ ใครอยากรู้ว่าใบนี้ได้ชั้นไหน
-- ต้องเทียบเลขแต้มกับ PICKEM_TIER_POINTS เอง (เหรียญ "นักทายแม่น" ของ OD-64 ทำแบบนั้น)
--
-- 🔴 การเดาย้อนนั้นถูกเฉพาะตอนที่แต้มของ 3 ชั้นไม่ซ้ำกัน (ตอนนี้ 10/7/4)
--    วันที่ทีมตั้งแต้มซ้ำกัน เช่น close = 10 เท่า spot_on:
--      - เหรียญจะนับใบชั้น close เป็น spot_on เงียบ ๆ
--      - และ **แถวเก่าจะแปลงย้อนไม่ได้อีกเลย** เพราะข้อมูลที่แยกสองชั้นออกจากกันหายไปแล้ว
--    ⇒ หน้าต่างของการ backfill ให้แม่น 100% คือ "ตอนนี้" เท่านั้น · migration นี้จึงมาก่อนที่จะมีใครแตะแต้ม
--
-- settleTx เป็นคนเขียนคอลัมน์นี้ และ pickemScoreFor() คืน tier มาให้อยู่แล้ว
-- (เดิมโค้ดรับ { points, tier } แล้วทิ้ง tier ทันที) ⇒ ฝั่งโค้ดแทบไม่มีอะไรเพิ่ม
--
-- NULL = ยังไม่ตัดสิน — ชุดเดียวกับ points_earned IS NULL เสมอ (unsettleTx ล้างทั้งคู่พร้อมกัน)

ALTER TABLE pickem_predictions
  ADD COLUMN tier ENUM('spot_on','close','side_only','wrong_side') NULL AFTER points_earned;

-- ★ เลข 10/7/4/0 ที่เขียนตรง ๆ ที่นี่ "ถูกต้อง" เพราะเป็นค่าของ PICKEM_TIER_POINTS
--   ณ วันที่แถวเก่าถูกตัดสิน ไม่ใช่ค่าปัจจุบัน · migration ต้องบันทึกอดีต ไม่ใช่อ่าน config วันนี้
--
-- 🔴 แต่มีแถวสองยุค และแปลงด้วยกฎเดียวไม่ได้
--
--   ยุคก่อน OD-56 (ก่อน migration 038): ทายแค่ "ฝั่ง" ไม่มีสกอร์เลย · PICKEM_POINTS = 10 แบนราบ
--     ⇒ "10" ของยุคนั้นหมายถึง **ทายฝั่งถูก** เท่านั้น ไม่ได้หมายถึงทายสกอร์แม่น
--     ⇒ ถ้าแปลงเป็น 'spot_on' ตามเลข เหรียญ "นักทายแม่น" (OD-64) จะนับใบที่ไม่เคยทายสกอร์ด้วย
--        ซึ่งให้เครดิตเกินจริง และไม่มีใครจับได้เพราะตัวเลขดูถูกต้องทุกทาง
--     ⇒ แยกด้วย `predicted_score_data IS NULL` ซึ่งเป็นร่องรอยเดียวที่บอกยุคของแถวได้
--        และให้ 'side_only' เพราะนั่นคือ "สิ่งเดียวที่เรารู้จริง" เกี่ยวกับแถวนั้น
--
--   ยุค OD-56 ขึ้นไป: 10/7/4/0 ตรงกับ 3 ชั้น + ทายฝั่งผิด
--
--   🔴 ผลข้างเคียงที่ยอมรับ: แถวยุคเก่าจะมี points_earned = 10 คู่กับ tier = 'side_only'
--      ซึ่ง "ไม่ตรงกัน" ตามตารางแต้มวันนี้ · ตั้งใจ — ประวัติแต้มที่ให้ไปแล้วห้ามแก้
--      (มันอยู่ใน users.total_points แล้ว) ส่วน tier ต้องบอกความจริงว่าแถวนั้นพิสูจน์อะไรได้
UPDATE pickem_predictions
   SET tier = CASE
                  WHEN points_earned = 0 THEN 'wrong_side'
                  WHEN predicted_score_data IS NULL THEN 'side_only'   -- ยุคก่อน OD-56
                  WHEN points_earned = 10 THEN 'spot_on'
                  WHEN points_earned =  7 THEN 'close'
                  WHEN points_earned =  4 THEN 'side_only'
              END
 WHERE points_earned IS NOT NULL;

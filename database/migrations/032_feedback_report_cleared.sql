-- มติ 30 ก.ย. 2569 — จำว่าความเห็นไหน "ตรวจแล้ว" ไม่ใช่จำแค่ว่า "ถูกรายงานอยู่"
--
-- is_reported ตอบได้แค่ว่าตอนนี้มีเรื่องค้างหรือไม่ พอผู้จัดกดปล่อยผ่าน (E17d) ธงลง
-- แต่ไม่มีอะไรจำว่าเคยตรวจ ⇒ ใครกด report ใหม่ (คนเดิมก็ได้) ธงขึ้นอีก ผู้จัดถูกแจ้งอีก
-- เท่ากับคนกลุ่มเดียวส่งเรื่องเดิมซ้ำได้ไม่จำกัด ทั้งที่ถูกตัดสินไปแล้วว่าไม่มีมูล
--
-- report_cleared_at NULL = ยังไม่ตรวจ (ค่าตั้งต้นของทุกความเห็น) · มีค่า = ตรวจแล้วปล่อยผ่าน
-- เก็บเป็นเวลาไม่ใช่ BOOLEAN เพราะอยากรู้ว่า "ตรวจเมื่อไร" ตอนไล่ย้อน ไม่ใช่แค่ว่าตรวจแล้ว
-- กลับเป็น NULL เมื่อเจ้าของแก้ข้อความ — สิ่งที่ผู้จัดตรวจผ่านคือข้อความนั้น ไม่ใช่แถวนั้น
ALTER TABLE tournament_feedback
  ADD COLUMN report_cleared_at DATETIME NULL AFTER is_reported;

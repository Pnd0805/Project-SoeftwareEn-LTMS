-- B1 — เปลี่ยนรหัสผ่านแล้วต้องเตะบัตรเก่าออก · มติ 6 ต.ค. 2569 (ทางเลือก ข)
-- ═══════════════════════════════════════════════════════════════════════════════
--
-- ปัญหาที่แก้: ตั้งรหัสผ่านใหม่สำเร็จ → รหัสเก่าล็อกอินไม่ได้ (ถูก)
-- แต่บัตร (JWT) ที่ออกไปก่อนเปลี่ยนรหัส **ยังใช้ได้จนหมดอายุเอง**
-- และปุ่มออกจากระบบไม่ได้ทำอะไรฝั่งเซิร์ฟเวอร์เลย (ตอบ 204 เฉย ๆ)
--
-- 🔴 เหตุผลหลักที่คนเปลี่ยนรหัสคือ "สงสัยว่ามีคนเข้าบัญชี"
--   แต่การเปลี่ยนรหัสไม่ได้เตะคนนั้นออก ⇒ สิ่งที่ผู้ใช้เชื่อว่าได้ ไม่ตรงกับที่ระบบทำ
--
-- ═══ วิธี: เลขรุ่นของบัตร (มติ ทางเลือก ข) ═══
-- บัญชีมีเลขรุ่น 1 ตัว · บัตรที่ออกพกเลขรุ่นตอนนั้นติดไปด้วย
-- เปลี่ยนรหัสผ่าน → บวกเลขรุ่น ⇒ บัตรที่พกเลขเก่าใช้ไม่ได้ทันทีทุกใบทุกเครื่อง
--
-- ★ ทำไมไม่เลือกทางเลือก ก (จดเวลาที่เปลี่ยนรหัส แล้วปฏิเสธบัตรที่ออกก่อนเวลานั้น)
--   ก เทียบด้วยเวลาซึ่งละเอียดแค่ระดับวินาที — บัตรที่ออกในวินาทีเดียวกับที่เปลี่ยนรหัสคาบเกี่ยวได้
--   และถ้าภายหลังอยากได้ "ออกจากระบบทุกเครื่อง" ต้องไปบวกเวลาหลอก ๆ ซึ่งอ่านไม่รู้เรื่อง
--   เลขรุ่นได้ความสามารถนั้นมาฟรีและความหมายตรงตัว (ยังไม่เปิดเป็น endpoint ในรอบนี้)
-- ★ ทำไมไม่เลือก ค (ลดอายุบัตรให้สั้นลง) — ไม่ได้แก้ปัญหา แค่ย่อหน้าต่างให้แคบลง
--   ผู้ใช้ต้องล็อกอินบ่อยขึ้น โดยที่คนแอบใช้บัญชียังอยู่ได้จนบัตรหมดอายุอยู่ดี
--
-- ★ ไม่มีคิวรีเพิ่มจากด่านตรวจบัตร — ด่านนั้นอ่านแถว users อยู่แล้วทุกคำขอ
-- ★ DEFAULT 0 ⇒ บัญชีเดิมทั้งหมดเป็นรุ่น 0 และบัตรเก่าที่ไม่มีช่องเลขรุ่นก็ถือเป็นรุ่น 0
--   ⇒ deploy แล้วไม่มีใครถูกเตะออกจากระบบ (ตั้งใจ — ไม่เอาผู้ใช้มารับผลของการ deploy)
-- ═══════════════════════════════════════════════════════════════════════════════

SET NAMES utf8mb4;

ALTER TABLE users
  ADD COLUMN token_version INT NOT NULL DEFAULT 0 AFTER email_verified;

-- ไม่มี backfill — DEFAULT 0 ให้ค่าที่ถูกต้องกับทุกแถวเดิมอยู่แล้ว

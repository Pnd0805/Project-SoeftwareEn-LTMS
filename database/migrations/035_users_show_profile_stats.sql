-- มติ 1 ต.ค. 2569 (OD-46) — ให้เจ้าตัวปิดการแสดงสถิติในหน้าโปรไฟล์ของตัวเองได้
--
-- ที่มา: feat/rewards-match-history เข้ามาพร้อม GET /users/:id/match-history ซึ่งเปิดสาธารณะ
-- ทำให้มีของสองอย่างอยู่ข้างกันแต่กฎคนละแบบ — รางวัลปิดได้รายชิ้น (user_rewards.is_displayed)
-- แต่ประวัติแมตช์กับสถิติรายคนปิดไม่ได้เลย ⇒ ไม่ใช่ข้อบกพร่อง (GET /users/:id/stats ก็ public
-- มาตั้งแต่แรก) แต่ "ปิดได้/ปิดไม่ได้" ของสองเส้นที่อยู่ข้างกันควรเป็นมติ ไม่ใช่ผลข้างเคียง
--
-- สวิตช์เดียวคุมทั้งสามเส้น (stats · match-history · career) ไม่แยกเป็นสามช่อง
-- เพราะถ้าปิดแค่ยอดรวมแล้วยังอ่านสถิติรายแมตช์ได้ = ปิดไม่จริง ผู้ใช้จะเข้าใจว่าปิดแล้วทั้งที่ยังเห็น
-- และหน้าตั้งค่าที่มีสามสวิตช์ซึ่งต้องปิดให้ครบจึงจะได้ผล เป็นการผลักภาระความเข้าใจไปให้ผู้ใช้
--
-- ขอบเขตที่ปิดได้ = **หน้าโปรไฟล์เท่านั้น**
-- ตารางคะแนน ผลแมตช์ และโหวต MVP ไม่แตะ เพราะนั่นเป็นข้อมูลของ "การแข่งขัน" ไม่ใช่ของโปรไฟล์
-- ถ้าให้ปิดตรงนั้นได้ จะกลายเป็นคนซ่อนผลการแข่งของตัวเองในทัวร์ที่คนอื่นต้องใช้ตัดสิน
--
-- DEFAULT 1 (เปิด) — คงพฤติกรรมเดิมของทุกแถวที่มีอยู่ ไม่มีใครถูกซ่อนเงียบ ๆ จาก migration นี้
-- ถ้าเลือก DEFAULT 0 หน้าโปรไฟล์ของทุกคนจะว่างทันทีที่ deploy โดยที่ไม่มีใครกดอะไรเลย
--
-- TINYINT(1) ไม่ใช่ ENUM เพราะเป็นค่าสองทางจริง ๆ (เปิด/ปิด) ไม่ใช่ชุดที่จะงอกเพิ่มทีหลัง
-- ถ้าวันหนึ่งต้องมี "เฉพาะคนที่ติดตาม" จะเป็น migration ใหม่ที่เปลี่ยนเป็น ENUM พร้อมกฎของมันเอง
ALTER TABLE users
  ADD COLUMN show_profile_stats TINYINT(1) NOT NULL DEFAULT 1 AFTER notification_prefs;

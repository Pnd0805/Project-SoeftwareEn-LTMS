-- OD-56 ก้าวที่ 3 (4 ต.ค. 2569) — เปลี่ยนความหมายของ tolerance จาก "คลาดรวมสองฝั่ง" เป็น "คลาดต่อฝั่ง"
--                                  และแยกเส้นของชั้น spot_on กับ close ออกเป็นสองคอลัมน์
--
-- ═══ ① ทำไมเลิกบวกความคลาดสองฝั่งเข้าด้วยกัน ═══
-- 039 คิดว่า `drift = |คลาดซ้าย| + |คลาดขวา|` แล้วเทียบกับเส้นเดียว ซึ่งมีผลข้างเคียง 2 อย่าง
-- ที่ไม่ได้ตั้งใจ:
--
--   ก) **ลงโทษกีฬาแต้มสูงสองเท่า** — ยิ่งสกอร์สูง ทั้งสองฝั่งยิ่งคลาดพร้อมกัน
--      บาสคลาดฝั่งละ 1 แต้มจาก ~100 (แม่นมาก) ได้ drift 2 เท่ากับฟุตบอลคลาดฝั่งละ 1 ประตูจาก 3
--
--   ข) **มองข้ามว่า "อ่านผลต่างถูก" คือการทายที่ดี** — ทาย 2-1 ได้จริง 3-2
--      ผลต่าง +1 ถูกเป๊ะ แค่ประเมินจำนวนประตูต่ำไปหนึ่ง แต่ drift = 2 ⇒ ร่วงไปชั้นพื้น
--      ขณะที่ทาย 2-1 ได้จริง 3-1 (ผลต่างผิดไป 1) drift = 1 ⇒ ได้ชั้นกลาง
--      = ให้รางวัลการทายที่แย่กว่ามากกว่า
--
-- ⇒ เปลี่ยนเป็น **ดูทีละฝั่ง แล้วยึดฝั่งที่แย่กว่า** (worst-link)
--      spot_on = ทุกฝั่งคลาด ≤ pickem_tolerance_exact
--      close   = ทุกฝั่งคลาด ≤ pickem_tolerance_close
--   ค่า tolerance จึงมีความหมายเดียวตลอด = "คลาดได้เท่าไรต่อฝั่ง"
--   ไม่ขึ้นกับว่าความคลาดไปกระจุกอยู่ฝั่งเดียวหรือกระจายสองฝั่ง
--
-- ═══ ② ทำไมสองคอลัมน์ ไม่ใช่คอลัมน์เดียวแล้วคูณสอง ═══
-- ทางเลือกที่พิจารณาคือเก็บ tol เดียวแล้วให้ `close = 2 × tol` แต่
--   - ฟุตบอลต้องการ (เป๊ะ 0 , ใกล้ 1) ซึ่ง 2 × 0 = 0 เขียนไม่ได้ ต้องใช้ tol = 0.5
--     ⇒ ต้องเปลี่ยนคอลัมน์เป็น DECIMAL ทั้งที่สกอร์เป็นจำนวนเต็มเสมอ (คลาดเป็นเศษไม่มีจริง)
--   - อัตราส่วน ×2 ถูกบังคับ — วันหนึ่งอยากได้บาส (5 , 8) จะทำไม่ได้
-- ⇒ สองคอลัมน์จำนวนเต็มพูดทั้งสองเส้นตรง ๆ อ่านตารางแล้วรู้ทันทีว่ากีฬานั้นให้คลาดได้เท่าไร
--   และปรับได้ด้วย UPDATE ไม่ต้องมี migration ใหม่
--
-- ═══ ③ ลบ pickem_score_tolerance ทิ้ง ไม่เก็บไว้ ═══
-- คอลัมน์นั้นเพิ่งเกิดใน 039 วันนี้และยังไม่มีข้อมูลจริงของใครผูกอยู่
-- ถ้าเก็บไว้จะมีคอลัมน์ tolerance สามตัวในตารางเดียว โดยสองตัวเท่านั้นที่โค้ดอ่าน
-- ⇒ คนที่มาอ่านทีหลังต้องเดาว่าตัวไหนจริง — แหล่งความจริงต้องมีที่เดียว

ALTER TABLE sport_types
  ADD COLUMN pickem_tolerance_exact INT NOT NULL DEFAULT 0 AFTER walkover_score,
  ADD COLUMN pickem_tolerance_close INT NOT NULL DEFAULT 0 AFTER pickem_tolerance_exact;

-- ★ กันค่าที่ทำให้ชั้นกลางหายไปเงียบ ๆ
--   ถ้า close < exact ชั้น close จะไม่มีทางยิงเลย เพราะอะไรที่ ≤ close ก็ ≤ exact ไปแล้ว
--   = ผู้เล่นเสียชั้น 7 แต้มไปโดยไม่มี error ฟ้อง ⇒ ให้ฐานปฏิเสธตั้งแต่ตอนเขียน
--   (สูตรใน utils/pickemScore.ts บีบค่าซ้ำอีกชั้นด้วย เผื่อข้อมูลมาจากทางอื่น)
ALTER TABLE sport_types
  ADD CONSTRAINT chk_sport_pickem_tolerance CHECK (pickem_tolerance_close >= pickem_tolerance_exact);

-- ค่าต่อกีฬา — หลักที่ใช้ตั้ง: **ชั้นสูงสุดควรเป็นแถบที่แคบที่สุดที่ยังเอื้อมถึงได้จริงในกีฬานั้น**
--
--   แบด / RoV / VALORANT  (0 , 0)  ทายฝั่งถูกแล้วเหลือสกอร์แค่ 2 ทางเลือก (2-0 / 2-1)
--                                  ชั้นเป๊ะง่ายอยู่แล้ว (~50%) ⇒ ไม่ต้องขยาย · ชั้นกลางไม่ยิงโดยเจตนา
--   ฟุตบอล                (0 , 1)  ทายสกอร์เป๊ะเป็นสิ่งที่คนดูบอลทายกันจริงและเกิดได้ (~15%)
--                                  ⇒ ชั้นเต็มควรหมายถึง "เป๊ะ" จริง ๆ · คลาดฝั่งละไม่เกิน 1 ประตู = ชั้นกลาง
--   บาสเกตบอล             (5 , 10) เป๊ะทั้งสองตัวแทบเป็นไปไม่ได้ (~0%) ⇒ **จำเป็น**ต้องเป็นแถบ
--                                  ไม่งั้นเพดานจริงของคนทายบาสคือ 7 ตลอดชีวิต ทั้งที่ทายแม่นเท่ากีฬาอื่น
UPDATE sport_types SET pickem_tolerance_exact = 0, pickem_tolerance_close = 1  WHERE name = 'ฟุตบอล';
UPDATE sport_types SET pickem_tolerance_exact = 5, pickem_tolerance_close = 10 WHERE name = 'บาสเกตบอล';

ALTER TABLE sport_types DROP COLUMN pickem_score_tolerance;
